#!/usr/bin/env node
/**
 * Generates deterministic CLI, MCP, and Release metadata for the Next.js static export.
 * Sources of truth:
 *   - ../package.json
 *   - ../tools/definitions.js (getToolList)
 *   - ../cli/args.js (COMMANDS, FLEET_VERBS, USAGE)
 *   - ../CHANGELOG.md
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.dirname(here);
const repoRoot = path.dirname(webRoot);
const target = path.join(webRoot, "lib", "catalog.generated.ts");

function sanitizePublicText(text) {
  return String(text || "")
    .replace(/D:[\\/]code[\\/][A-Za-z0-9_.-]+/gi, "/path/to/repo")
    .replace(/\bHELLOWORLD\b/g, "workstation-b")
    .replace(/\bMMCH\b/g, "workstation-a")
    .replace(/\bmmch\b/g, "workstation-a")
    .trim();
}

function parseCliArgsSource(source) {
  const commandsMatch = source.match(/const COMMANDS\s*=\s*\[([^\]]+)\]/);
  const fleetMatch = source.match(/const FLEET_VERBS\s*=\s*\[([^\]]+)\]/);
  const parseList = (m) =>
    m
      ? m[1]
          .split(",")
          .map((s) => s.trim().replace(/^["']|["']$/g, ""))
          .filter(Boolean)
      : [];
  return {
    commands: parseList(commandsMatch),
    fleetVerbs: parseList(fleetMatch),
  };
}

function parseChangelogHighlights(changelog) {
  const entries = [];
  const headingRe = /^##\s+\[?([^\]\s]+)\]?(?:\s+\(([^)]+)\))?/gm;
  let match;
  while ((match = headingRe.exec(changelog)) !== null && entries.length < 6) {
    entries.push({
      version: match[1],
      date: match[2] || "",
    });
  }
  return entries;
}

async function main() {
  const pkgRaw = await readFile(path.join(repoRoot, "package.json"), "utf8");
  const pkg = JSON.parse(pkgRaw);
  if (!pkg?.version || !pkg?.name) {
    throw new Error("package.json missing required name or version");
  }

  const defsUrl = pathToFileURL(path.join(repoRoot, "tools", "definitions.js")).href;
  const defsMod = await import(defsUrl);
  const rawTools = typeof defsMod.getToolList === "function" ? defsMod.getToolList() : [];
  if (!Array.isArray(rawTools) || rawTools.length === 0) {
    throw new Error("tools/definitions.js getToolList() returned no MCP tools");
  }
  const mcpTools = [...rawTools]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((tool) => {
      const schema = tool.inputSchema || {};
      const props = schema.properties || {};
      const required = Array.isArray(schema.required) ? schema.required : [];
      return {
        name: tool.name,
        description: sanitizePublicText(tool.description),
        required,
        params: Object.entries(props).map(([key, val]) => ({
          name: key,
          type: String(val?.type || (Array.isArray(val?.enum) ? "enum" : "any")),
          description: sanitizePublicText(val?.description),
          required: required.includes(key),
          enumValues: Array.isArray(val?.enum) ? val.enum.map(String) : [],
        })),
      };
    });

  const cliArgsSrc = await readFile(path.join(repoRoot, "cli", "args.js"), "utf8");
  const cliParsed = parseCliArgsSource(cliArgsSrc);
  if (cliParsed.commands.length === 0 || cliParsed.fleetVerbs.length === 0) {
    throw new Error("cli/args.js yielded empty COMMANDS or FLEET_VERBS");
  }
  const cliArgsMod = await import(pathToFileURL(path.join(repoRoot, "cli", "args.js")).href);

  const changelogSrc = await readFile(path.join(repoRoot, "CHANGELOG.md"), "utf8");
  const changelogEntries = parseChangelogHighlights(changelogSrc);

  const data = {
    packageName: pkg.name,
    version: pkg.version,
    nodeEngine: pkg.engines?.node || ">=20.0.0",
    license: pkg.license || "MIT",
    ossBaselineTag: "v1.31.0-oss.0",
    repositoryUrl: "https://github.com/programinglive/dev-workflow",
    repositoryVisibility: "PRIVATE",
    npmPubliclyPublished: false,
    mcpToolCount: mcpTools.length,
    mcpTools,
    mcpPrompts: [
      {
        name: "workflow_reminder",
        description: "Reminds the coding agent of required DevWorkflow governance gates for the current task.",
      },
      {
        name: "pre_commit_checklist",
        description: "Summarizes Definition of Done, documentation, and test verification before committing.",
      },
    ],
    cli: {
      commands: cliParsed.commands,
      fleetVerbs: cliParsed.fleetVerbs,
      usage: String(cliArgsMod.USAGE || "").trim(),
    },
    changelogEntries,
  };

  const out = `// Generated by web/scripts/generate-docs-data.mjs — do not edit manually.\nexport const GENERATED_CATALOG = ${JSON.stringify(data, null, 2)} as const;\n`;
  await writeFile(target, out, "utf8");
  console.log(`catalog: ${mcpTools.length} MCP tools, ${cliParsed.commands.length} CLI commands -> ${path.relative(webRoot, target)}`);
}

main().catch((err) => {
  console.error(`Failed to generate docs catalog: ${err.message}`);
  process.exit(1);
});
